// Оценка высоты текста в дюймах. Нужна не для красоты: pptxgenjs не обрезает
// переполнение, а разливает его вверх и вниз от центра блока – заголовок
// карточки молча уезжает под текст. Поэтому меряем на сборке и падаем.
function textHeight(txt, wIn, fontSize, lineSpacingPt) {
  const cpl = Math.max(8, Math.floor(wIn * 96 / (fontSize * 0.545)));
  let lines = 0;
  for (const para of String(txt).split("\n")) {
    lines += para.length ? Math.ceil(para.length / cpl) : 0.75;
  }
  return lines * lineSpacingPt / 72;
}
function fits(what, txt, wIn, hIn, fontSize, lineSpacingPt) {
  const need = textHeight(txt, wIn, fontSize, lineSpacingPt);
  if (need > hIn + 0.02) {
    throw new Error(
      `${what}: текст не помещается – нужно ${need.toFixed(2)}", есть ${hIn.toFixed(2)}". ` +
      `Начало: «${String(txt).slice(0, 60)}…»`);
  }
}

function stat(s, x, y, w, big, label, col) {
  s.addShape(p.ShapeType.roundRect, { x, y, w, h:1.86, fill:{color:PAPER}, rectRadius:0.06 });
  s.addText(big, { x:x+0.02, y:y+0.18, w:w-0.04, h:0.80, isTextBox:true, margin:0,
    fontFace:HEAD, fontSize:34, color:col, bold:true, align:"center", valign:"top" });
  fits("stat/label", label, w-0.44, 0.76, 11.5, 14);
  s.addText(label, { x:x+0.22, y:y+1.00, w:w-0.44, h:0.76, isTextBox:true, margin:0,
    fontFace:BODY, fontSize:11.5, color:MUTED, align:"center", lineSpacing:14, valign:"top" });
}

// Карточка: заголовку отведено две строки, тело всегда ниже них.
const CARD_TTL_H = 0.52, CARD_BODY_Y = 0.78;
function card(s, x, y, w, h, ttl, body, col) {
  s.addShape(p.ShapeType.roundRect, { x, y, w, h, fill:{color:PAPER}, rectRadius:0.06 });
  fits(`card/заголовок «${ttl.slice(0,28)}»`, ttl, w-0.56, CARD_TTL_H, 15.5, 19);
  s.addText(ttl, { x:x+0.28, y:y+0.20, w:w-0.56, h:CARD_TTL_H, isTextBox:true, margin:0,
    fontFace:HEAD, fontSize:15.5, color:col||INK, bold:true, valign:"top" });
  const bodyH = h - CARD_BODY_Y - 0.20;
  fits(`card «${ttl.slice(0,28)}»`, body, w-0.56, bodyH, 12.5, 17);
  s.addText(body, { x:x+0.28, y:y+CARD_BODY_Y, w:w-0.56, h:bodyH, isTextBox:true, margin:0,
    fontFace:BODY, fontSize:12.5, color:MUTED, lineSpacing:17, valign:"top" });
}

